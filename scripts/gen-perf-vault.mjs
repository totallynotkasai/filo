/**
 * gen-perf-vault — synthetic vault generator for cold-start perf testing.
 *
 * Generates a vault with N markdown files plus a representative spread of
 * tags, frontmatter, and inline links. Used to measure cold-start time
 * (target: <3s open → first paint per the design doc).
 *
 * Usage:
 *   node scripts/gen-perf-vault.mjs [outDir=./perf-vault] [count=1000]
 *
 * To measure cold-start:
 *   1. node scripts/gen-perf-vault.mjs ./perf-vault 1000
 *   2. npm run dev
 *   3. Open the vault directory from the HomeScreen, watch DevTools
 *      Performance tab for the first-paint timestamp after the dialog
 *      closes.
 *
 * Tracked in IMPL_PLAN_2026-05-25_v2 G.3.
 */
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

const outDir = resolve(process.argv[2] ?? './perf-vault');
const count = Number.parseInt(process.argv[3] ?? '1000', 10);

if (!Number.isFinite(count) || count < 1) {
  console.error('Usage: node scripts/gen-perf-vault.mjs [outDir] [count]');
  process.exit(1);
}

if (existsSync(outDir)) {
  console.error(`Refusing to overwrite existing directory: ${outDir}`);
  console.error('Delete or choose a different path first.');
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
mkdirSync(join(outDir, '.filo'), { recursive: true });

// Roughly 20 tag pools, ~50 files per tag on average — exercises the tag
// index and MiniSearch tokeniser at realistic fan-out.
const TAGS = [
  'project', 'meeting', 'idea', 'todo', 'reference',
  'archive', 'personal', 'work', 'research', 'draft',
  'review', 'urgent', 'someday', 'question', 'answer',
  'code', 'design', 'planning', 'retrospective', 'spike',
];

// Mix of folder depths so the spatial / sidebar trees aren't all flat.
const FOLDERS = ['', 'projects/', 'projects/alpha/', 'projects/beta/', 'meetings/', 'reference/', 'archive/2025/'];

function pick(arr, n) {
  const out = [];
  const pool = [...arr];
  for (let i = 0; i < n && pool.length > 0; i++) {
    const j = Math.floor(Math.random() * pool.length);
    out.push(pool.splice(j, 1)[0]);
  }
  return out;
}

const created = new Set();
for (let i = 0; i < count; i++) {
  const folder = FOLDERS[i % FOLDERS.length];
  const tags = pick(TAGS, 2 + (i % 3));
  const title = `Note ${String(i + 1).padStart(4, '0')}`;
  const path = `${folder}note-${String(i + 1).padStart(4, '0')}.md`;
  if (created.has(path)) continue;
  created.add(path);

  const abs = join(outDir, path);
  mkdirSync(join(outDir, folder), { recursive: true });

  const front = [
    '---',
    `title: ${title}`,
    `tags:`,
    ...tags.map((t) => `  - ${t}`),
    `created: 2026-${String((i % 12) + 1).padStart(2, '0')}-${String((i % 28) + 1).padStart(2, '0')}`,
    '---',
    '',
  ].join('\n');

  // ~30 lines of body, with a handful of internal links to exercise
  // link-resolution paths.
  const linkTarget = `note-${String(((i + 7) % count) + 1).padStart(4, '0')}`;
  const body = [
    `# ${title}`,
    '',
    `This is a synthetic note generated by gen-perf-vault.mjs.`,
    `It exists to exercise the vault open / index / search pipeline at`,
    `representative fan-out without containing meaningful content.`,
    '',
    '## Section A',
    '',
    `Tags: ${tags.map((t) => `#${t}`).join(' ')}.`,
    `Related: [[${linkTarget}]].`,
    '',
    '## Section B',
    '',
    'Lorem ipsum dolor sit amet, consectetur adipiscing elit. Sed do',
    'eiusmod tempor incididunt ut labore et dolore magna aliqua. Ut enim',
    'ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut',
    'aliquip ex ea commodo consequat.',
    '',
    '## Section C',
    '',
    '- bullet 1',
    '- bullet 2',
    '- bullet 3',
    '',
    '```ts',
    'const x = 1;',
    'function f() { return x; }',
    '```',
    '',
  ].join('\n');

  writeFileSync(abs, front + body, 'utf8');
}

console.log(`[gen-perf-vault] OK — generated ${created.size} files in ${outDir}`);
console.log('Next: npm run dev → open this directory as a vault → time the first paint.');
