/**
 * Generates a large vault for the performance script (`measure.mjs`).
 *
 *   node scripts/perf/genVault.mjs <outDir> [noteCount=5000]
 *
 * Notes: nested folders, frontmatter with tags and task fields (some recurring),
 * a mix of Markdown features, some CRLF / BOM files, a few notes without
 * frontmatter and one very large note. Boards (v8, written directly):
 *   - "Kanban 300"   3 columns × 100 cards
 *   - "Kanban 102"   3 columns × 34 cards
 *   - "Task List 400" 400 tasks in 4 sections, manual sort
 *   - "Mind Map 400" 400 text tiles in a 20 × 20 grid
 * Also a 2,000-note folder (`Bulk/`) for the sidebar expand measurement.
 *
 * Deterministic (fixed seed), so before / after numbers compare like for like.
 * Refuses to write into an existing folder that isn't a vault it made.
 */
import fs from 'node:fs';
import path from 'node:path';

const [, , outArg, countArg] = process.argv;
if (!outArg) {
  console.error('Usage: node scripts/perf/genVault.mjs <outDir> [noteCount=5000]');
  process.exit(1);
}
const outDir = path.resolve(outArg);
const N = Number(countArg ?? 5000);
const MARKER = path.join(outDir, '.filo', 'perf-vault');
if (fs.existsSync(outDir) && !fs.existsSync(MARKER)) {
  console.error(`Refusing to overwrite ${outDir}: it isn't a vault this script made.`);
  process.exit(1);
}
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(path.join(outDir, '.filo'), { recursive: true });
fs.writeFileSync(MARKER, 'generated by scripts/perf/genVault.mjs\n');

let seed = 42;
const rnd = () => ((seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const words = 'alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima mike november oscar papa quebec romeo sierra tango uniform victor whiskey xray yankee zulu dragon castle river forest magic sword shadow ember frost storm'.split(' ');
const sentence = (n) => Array.from({ length: n }, () => pick(words)).join(' ');
const tags = ['character', 'place', 'lore', 'plot', 'draft', 'todo', 'idea', 'research', 'world/magic', 'world/history', 'world/geo', 'chapter'];
const folders = ['Characters', 'Places', 'Lore/Magic', 'Lore/History', 'Chapters/Act 1', 'Chapters/Act 2', 'Chapters/Act 3', 'Research', 'Inbox', 'Tasks'];
for (const f of [...folders, 'Bulk']) fs.mkdirSync(path.join(outDir, f), { recursive: true });

const bodies = [
  () => `# ${sentence(3)}\n\n${sentence(40)}\n\n## Notes\n\n- ${sentence(6)}\n- ${sentence(5)}\n  - ${sentence(4)}\n\n${sentence(30)}\n`,
  () => `${sentence(20)} **${sentence(2)}** and *${sentence(2)}* with \`code\`.\n\n> ${sentence(12)}\n\n1. ${sentence(4)}\n2. ${sentence(4)}\n\n[link](https://example.com/${pick(words)})\n`,
  () => `| Name | Value |\n| --- | --- |\n| ${pick(words)} | ${pick(words)} |\n| ${pick(words)} | ${pick(words)} |\n\n\`\`\`js\nconst x = ${Math.floor(rnd() * 100)};\n\`\`\`\n\n- [ ] ${sentence(3)}\n- [x] ${sentence(3)}\n`,
  () => `${sentence(80)}\n\n${sentence(60)}\n\n${sentence(70)}\n`,
];

const pad = (n) => String(n).padStart(2, '0');
function writeNote(folder, i, { task = false } = {}) {
  const title = `${pick(words)} ${pick(words)} ${i}`;
  const fileName = `${title.replace(/^./, (c) => c.toUpperCase())}.md`;
  const noteTags = Array.from(new Set([pick(tags), pick(tags)])).slice(0, 1 + Math.floor(rnd() * 2));
  const fm = [`title: ${title}`, `tags: [${noteTags.join(', ')}]`];
  if (task) {
    fm.push(`completed: ${rnd() < 0.3}`);
    fm.push(`dueDate: 2026-${pad(1 + Math.floor(rnd() * 12))}-${pad(1 + Math.floor(rnd() * 28))}`);
    fm.push(`priority: ${pick(['low', 'medium', 'high'])}`);
    if (rnd() < 0.1) fm.push('recurrence: weekly');
  }
  if (rnd() < 0.05) fm.push('# a comment the user wrote', 'zip: 02134');
  let text = `---\n${fm.join('\n')}\n---\n\n${pick(bodies)()}`;
  if (rnd() < 0.1) text = text.replace(/\n/g, '\r\n');
  const bom = rnd() < 0.03 ? String.fromCharCode(0xfeff) : '';
  fs.writeFileSync(path.join(outDir, folder, fileName), bom + text, 'utf8');
  return path.posix.join(folder, fileName);
}

const tasks = [];
const other = [];
const bulkCount = Math.min(2000, Math.floor(N * 0.4));
for (let i = 0; i < N - bulkCount; i++) {
  const folder = i < 900 ? 'Tasks' : pick(folders.filter((f) => f !== 'Tasks'));
  const p = writeNote(folder, i, { task: folder === 'Tasks' });
  (folder === 'Tasks' ? tasks : other).push(p);
}
for (let i = 0; i < bulkCount; i++) writeNote('Bulk', N + i);
for (let i = 0; i < 20; i++) fs.writeFileSync(path.join(outDir, 'Inbox', `Plain ${i}.md`), `${sentence(30)}\n`);
fs.writeFileSync(path.join(outDir, 'Research', 'Huge note.md'), `---\ntitle: Huge note\n---\n\n` + Array.from({ length: 4000 }, () => sentence(15)).join('\n\n') + '\n');

// ── Boards ──
const now = 1790000000000;
let idn = 0;
const id = (p) => `${p}${String(idn++).padStart(10, '0')}`;
const textDef = (filePath) => ({ id: id('g'), type: 'text', filePath, style: { headerColor: '', bodyColor: '' }, createdAt: now, updatedAt: now });
const boardHead = (bid, name, type, settings) => ({ id: bid, name, emoji: '', createdAt: now, updatedAt: now, type, settings: { backgroundColor: '', defaultFolder: '', ...settings, defaults: {} } });
const save = (name, board, tileDefs) => fs.writeFileSync(path.join(outDir, `${name}.board.json`), JSON.stringify({ version: 8, board, tileDefs, connections: {}, frames: [] }, null, 2));

function kanban(name, bid, perColumn, offset) {
  const tileDefs = {};
  const columns = ['To do', 'Doing', 'Done'].map((title, ci) => {
    const tilePlacements = [];
    for (let i = 0; i < perColumn; i++) {
      const d = textDef(tasks[(offset + ci * perColumn + i) % tasks.length]);
      tileDefs[d.id] = d;
      tilePlacements.push({ tileId: d.id, position: i });
    }
    return { id: `${bid.slice(0, 6)}col${ci}xx`, title, position: ci, collapsed: false, tilePlacements };
  });
  save(name, { ...boardHead(bid, name, 'kanban', { accentColor: '', lastView: { sortBy: 'manual', filterTags: [], filterProp: null } }), columns }, tileDefs);
}
kanban('Kanban 300', 'perfkanban30', 100, 0);
kanban('Kanban 102', 'perfkanban10', 34, 300);

{
  const tileDefs = {};
  const taskRows = [];
  for (let i = 0; i < 400; i++) {
    const d = textDef(tasks[(400 + i) % tasks.length]);
    tileDefs[d.id] = d;
    taskRows.push({ tileId: d.id, position: i });
  }
  const sections = [0, 1, 2, 3].map((s) => ({ id: `sec_perf${s}xxxx`, title: `Section ${s + 1}`, position: s * 100, collapsed: false }));
  save('Task List 400', {
    ...boardHead('perftasklist', 'Task List 400', 'tasklist', {
      accentColor: '', groupBy: 'status', sortBy: 'manual',
      lastView: { filterTags: [], filterStatus: null, filterPriority: null, showCompleted: true, smartList: 'all' },
    }),
    tasks: taskRows, sections, collapsedSubtasks: [],
  }, tileDefs);
}

{
  const tileDefs = {};
  const placements = {};
  for (let i = 0; i < 400; i++) {
    const d = textDef(other[i % other.length]);
    tileDefs[d.id] = d;
    placements[d.id] = { x: (i % 20) * 280, y: Math.floor(i / 20) * 200, width: 240, height: 160, locked: false, faded: false, frameless: false };
  }
  save('Mind Map 400', {
    ...boardHead('perfmindmap4', 'Mind Map 400', 'mindmap', { semanticZoom: true, snapToGrid: false, connectionsVisible: true, labelsVisible: true }),
    placements, inlineTiles: {}, connections: [], frames: [], waypoints: [], groups: [], viewport: { x: 0, y: 0, scale: 1 },
  }, tileDefs);
}

fs.writeFileSync(path.join(outDir, '.filo', 'perf-notes.json'), JSON.stringify({ tasks, other }));
console.log(`wrote ${N + 21} notes and 4 boards to ${outDir}`);
